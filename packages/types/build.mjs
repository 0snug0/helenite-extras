// Writes dist/helenite.d.ts: `declare module 'helenite'`, generated from the runtime module
// (packages/obsidian-api/src/helenite-module.ts) so the types cannot drift from what `require('helenite')` returns.
//
// tsc emits declarations for the module and everything it imports; this script keeps only the files reachable from
// helenite-module.d.ts, wraps each in an ambient `declare module 'helenite/internal/<path>'`, and points every import
// at those names. An import that leaves that set fails the build, so the file never depends on packages a plugin
// author does not have, except the stand-ins in OPAQUE.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');
const tmp = join(here, 'dist/.emit');
const out = join(tmp, 'out');
const ENTRY = 'packages/obsidian-api/src/helenite-module';
const PACKAGES = { '@helenite/ui': 'packages/ui/src/index' };
// `AnyApp` is `App | any`, i.e. any: the parts take whichever app object the plugin holds (Obsidian's `this.app`).
const OPAQUE = { 'packages/obsidian-api/src/app': 'export type App = any;' };

rmSync(tmp, { recursive: true, force: true });
mkdirSync(tmp, { recursive: true });
const tsconfig = join(tmp, 'tsconfig.json');
writeFileSync(tsconfig, JSON.stringify({
  extends: join(root, 'tsconfig.base.json'),
  compilerOptions: {
    noEmit: false,
    declaration: true,
    emitDeclarationOnly: true,
    isolatedModules: false,
    rootDir: root,
    outDir: out,
    paths: Object.fromEntries(Object.entries(PACKAGES).map(([name, p]) => [name, [join(root, `${p}.ts`)]])),
  },
  files: [join(root, `${ENTRY}.ts`)],
}));
execFileSync(join(root, 'node_modules/.bin/tsc'), ['-p', tsconfig], { stdio: 'inherit' });

const idOf = (key) => `helenite/internal/${key.replace(/^packages\//, '')}`;
const blocks = new Map();

function resolveKey(spec, fromKey) {
  if (spec in PACKAGES) return PACKAGES[spec];
  if (!spec.startsWith('.')) throw new Error(`${fromKey}.d.ts imports "${spec}", which plugin authors do not have`);
  const base = relative(root, resolve(root, dirname(fromKey), spec));
  if (base in OPAQUE) return base;
  for (const key of [base, `${base}/index`]) if (existsSync(join(out, `${key}.d.ts`))) return key;
  throw new Error(`${fromKey}.d.ts: cannot find the declarations of "${spec}"`);
}

function add(key) {
  if (blocks.has(key)) return;
  if (key in OPAQUE) return void blocks.set(key, OPAQUE[key]);
  blocks.set(key, '');
  const src = readFileSync(join(out, `${key}.d.ts`), 'utf8');
  const body = src
    .replace(/(from\s+|import\(\s*)(['"])([^'"]+)\2/g, (_, lead, q, spec) => {
      const target = resolveKey(spec, key);
      add(target);
      return `${lead}${q}${idOf(target)}${q}`;
    })
    // Inside `declare module` everything is already ambient: a second `declare` is an error.
    .replace(/^(export )?declare /gm, '$1')
    .replace(/^export \{\};\n?/gm, '');
  blocks.set(key, body);
}

add(ENTRY);
const indent = (s) => s.trimEnd().split('\n').map((l) => (l ? `  ${l}` : l)).join('\n');
const parts = [
  '// Generated by packages/types/build.mjs from packages/obsidian-api/src/helenite-module.ts. Do not edit.',
  '// helenite/internal/* are implementation modules; import only from \'helenite\'.',
  '',
  "declare module 'helenite' {",
  `  import type { heleniteModule } from '${idOf(ENTRY)}';`,
  '  /** The running Helenite version, e.g. for comparing against your manifest\'s "helenite" range. */',
  '  export const version: typeof heleniteModule.version;',
  '  /** Helenite\'s design-system parts. */',
  '  export const ui: typeof heleniteModule.ui;',
  '}',
  ...[...blocks].map(([key, body]) => `\ndeclare module '${idOf(key)}' {\n${indent(body)}\n}`),
  '',
];
writeFileSync(join(here, 'dist/helenite.d.ts'), parts.join('\n'));
rmSync(tmp, { recursive: true, force: true });
console.log(`wrote dist/helenite.d.ts (${blocks.size} modules)`);
